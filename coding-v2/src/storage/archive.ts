import {
  createCopy, type LegacyDoc, type LegacyImage,
  type LegacySnapshot, type Source
} from './documents';

const SCHEMA = 'coding-v2-safe-backup';
const MARK = '$codingV2BinaryType';
interface Archive { schema: typeof SCHEMA; version: 1; exportedAt: string; entries: unknown[]; }
function bytesToBase64(bytes: Uint8Array): string {
  const step = 16_384;
  let encoded = '';
  for (let pos = 0; pos < bytes.length; pos += step) {
    encoded += String.fromCharCode(...bytes.subarray(pos, pos + step));
  }
  return btoa(encoded);
}
function base64ToBytes(value: string): Uint8Array<ArrayBuffer> {
  const binary = atob(value);
  const data = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) data[i] = binary.charCodeAt(i);
  return data;
}
async function encode(value: unknown, seen = new WeakSet<object>()): Promise<unknown> {
  if (value instanceof Blob) {
    return { [MARK]: 'blob', mime: value.type, base64: bytesToBase64(new Uint8Array(await value.arrayBuffer())) };
  }
  if (value instanceof ArrayBuffer) return { [MARK]: 'buffer', base64: bytesToBase64(new Uint8Array(value)) };
  if (ArrayBuffer.isView(value)) {
    return { [MARK]: 'typed', ctor: value.constructor.name, base64: bytesToBase64(new Uint8Array(value.buffer, value.byteOffset, value.byteLength)) };
  }
  if (value instanceof Date) return { [MARK]: 'date', iso: value.toISOString() };
  if (value === null || typeof value !== 'object') return value;
  if (seen.has(value)) throw new Error('Não é possível exportar um objeto circular.');
  seen.add(value);
  const out: Record<string, unknown> | unknown[] = Array.isArray(value) ? [] : {};
  if (Array.isArray(out) && Array.isArray(value)) {
    for (const item of value) out.push(await encode(item, seen));
  } else {
    for (const [key, item] of Object.entries(value)) {
      if (key === '__proto__' || key === 'constructor' || key === 'prototype') throw new Error('O documento contém uma chave reservada.');
      (out as Record<string, unknown>)[key] = await encode(item, seen);
    }
  }
  seen.delete(value);
  return out;
}
function decode(value: unknown): unknown {
  if (value === null || typeof value !== 'object') return value;
  if (Array.isArray(value)) return value.map(decode);
  const object = value as Record<string, unknown>;
  if (Object.hasOwn(object, MARK)) {
    if (typeof object[MARK] !== 'string') throw new Error('Marcador inválido.');
    switch (object[MARK]) {
      case 'blob':
        if (typeof object.base64 !== 'string') throw new Error('Blob sem dados.');
        return new Blob([base64ToBytes(object.base64)], { type: typeof object.mime === 'string' ? object.mime : '' });
      case 'buffer':
        if (typeof object.base64 !== 'string') throw new Error('ArrayBuffer sem dados.');
        return base64ToBytes(object.base64).buffer;
      case 'typed': {
        if (typeof object.base64 !== 'string') throw new Error('Dados binários ausentes.');
        const buffer = base64ToBytes(object.base64).buffer;
        // DataView / typed arrays generated by the legacy code remain binary.
        const ctor = object.ctor;
        if (ctor === 'Uint8Array') return new Uint8Array(buffer);
        if (ctor === 'Uint16Array') return new Uint16Array(buffer);
        if (ctor === 'Uint32Array') return new Uint32Array(buffer);
        if (ctor === 'Int8Array') return new Int8Array(buffer);
        if (ctor === 'Int16Array') return new Int16Array(buffer);
        if (ctor === 'Int32Array') return new Int32Array(buffer);
        if (ctor === 'Float32Array') return new Float32Array(buffer);
        if (ctor === 'Float64Array') return new Float64Array(buffer);
        if (ctor === 'DataView') return new DataView(buffer);
        throw new Error('Formato binário desconhecido: ' + String(ctor));
      }
      case 'date': {
        if (typeof object.iso !== 'string') throw new Error('Data inválida.');
        const date = new Date(object.iso);
        if (Number.isNaN(date.getTime())) throw new Error('Data inválida.');
        return date;
      }
      default: throw new Error('Formato de backup desconhecido.');
    }
  }
  const result: Record<string, unknown> = Object.create(null) as Record<string, unknown>;
  for (const [key, item] of Object.entries(object)) {
    if (key === '__proto__' || key === 'constructor' || key === 'prototype') throw new Error('Chave de backup inválida.');
    result[key] = decode(item);
  }
  return result;
}
const isSnapshot = (value: unknown): value is LegacySnapshot => {
  if (!value || typeof value !== 'object') return false;
  const item = value as LegacySnapshot;
  return !!item.doc && typeof item.doc.id === 'string' && !!item.doc.id && Array.isArray(item.images)
    && ['indexeddb', 'localStorage', 'backup'].includes(item.source);
};

/** Binary-safe JSON backup: images are included, NEVER just metadata. */
export async function encodeBackup(snapshots: readonly LegacySnapshot[]): Promise<string> {
  const archive: Archive = { schema: SCHEMA, version: 1, exportedAt: new Date().toISOString(), entries: [] };
  for (const snapshot of snapshots) {
    if (!isSnapshot(snapshot)) throw new Error('Documento inválido no backup.');
    archive.entries.push(await encode(snapshot));
  }
  return JSON.stringify(archive, null, 2);
}

export function decodeBackup(text: string): LegacySnapshot[] {
  const value: unknown = JSON.parse(text);
  if (!value || typeof value !== 'object') throw new Error('Arquivo não é um backup reconhecido.');
  const archive = value as Archive;
  if (archive.schema !== SCHEMA || archive.version !== 1 || !Array.isArray(archive.entries)) {
    throw new Error('Formato de backup não reconhecido (requer Coding 2.0, versão 1).');
  }
  return archive.entries.map((entry) => {
    const snapshot = decode(entry);
    if (!isSnapshot(snapshot)) throw new Error('Documento incompleto no backup.');
    return snapshot;
  });
}

export async function importBackupToCopies(text: string): Promise<number> {
  const entries = decodeBackup(text);
  // Each import creates an INDEPENDENT copy. No legacy document is replaced.
  for (const entry of entries) {
    const snapshot: LegacySnapshot = {
      source: 'backup', doc: entry.doc as LegacyDoc, images: entry.images as LegacyImage[]
    };
    await createCopy(snapshot);
  }
  return entries.length;
}

export function downloadBackup(text: string, filename: string): void {
  const url = URL.createObjectURL(new Blob([text], { type: 'application/json;charset=utf-8' }));
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.append(anchor);
  anchor.click();
  anchor.remove();
  setTimeout(() => URL.revokeObjectURL(url), 5000);
}
